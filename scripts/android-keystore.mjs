/**
 * One-time: create a release keystore + android/keystore.properties.
 *
 * Usage:
 *   FIELD_KEYSTORE_PASSWORD='…' npm run android:keystore
 *
 * Does not overwrite an existing keystore. Keep the .jks and passwords safe —
 * losing them means you cannot update the same sideloaded app.
 */
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const androidDir = join(ROOT, "android");
const keystoreDir = join(androidDir, "keystore");
const keystoreFile = join(keystoreDir, "field-release.jks");
const propsFile = join(androidDir, "keystore.properties");
const alias = process.env.FIELD_KEY_ALIAS || "field";
const password = process.env.FIELD_KEYSTORE_PASSWORD;

if (!password || password.length < 6) {
  console.error(
    "Set FIELD_KEYSTORE_PASSWORD to a password (6+ chars) before running.",
  );
  process.exit(1);
}

if (existsSync(keystoreFile)) {
  console.error(`Keystore already exists: ${keystoreFile}`);
  console.error("Refuse to overwrite. Delete it only if you intend to invalidate old installs.");
  process.exit(1);
}

mkdirSync(keystoreDir, { recursive: true });

const dname =
  process.env.FIELD_KEYSTORE_DNAME ||
  "CN=Field, OU=Field, O=QCDLV, L=Unknown, ST=Unknown, C=US";

console.log(`Creating ${keystoreFile} (alias=${alias})…`);
execFileSync(
  "keytool",
  [
    "-genkeypair",
    "-v",
    "-storetype",
    "PKCS12",
    "-keystore",
    keystoreFile,
    "-alias",
    alias,
    "-keyalg",
    "RSA",
    "-keysize",
    "2048",
    "-validity",
    "10000",
    "-storepass",
    password,
    "-keypass",
    password,
    "-dname",
    dname,
  ],
  { stdio: "inherit" },
);

const props = [
  "# Generated by npm run android:keystore — do not commit.",
  "storeFile=keystore/field-release.jks",
  `storePassword=${password}`,
  `keyAlias=${alias}`,
  `keyPassword=${password}`,
  "",
].join("\n");

if (existsSync(propsFile)) {
  console.warn(`Leaving existing ${propsFile} in place (keystore created).`);
} else {
  writeFileSync(propsFile, props, { encoding: "utf8", mode: 0o600 });
  console.log(`Wrote ${propsFile}`);
}

console.log(`
Release signing is ready.
Keep android/keystore/field-release.jks and the password somewhere durable.
Next: npm run apk:staging
`);
